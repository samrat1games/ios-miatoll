#!/usr/bin/env python3
"""Generate shim/board.h from board/<name>.json.  Usage: genboard.py [name]"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import board
b = board.load(sys.argv[1] if len(sys.argv) > 1 else 'miatoll', quiet=True)
m = {'FB_BASE': 'fb', 'UFS_BASE': 'ufs', 'IMEM_RESTART_REASON': 'imem_restart_reason',
     'PSHOLD': 'pshold', 'GICD_BASE': 'gicd', 'GICR_BASE': 'gicr', 'GICR_SIZE': 'gicr_size'}
out = ['/* generated by tools/genboard.py from board/%s.json - do not edit */' % b['name'],
       '#ifndef BOARD_H', '#define BOARD_H']
out += ['#define %s\t0x%xUL' % (k, b[v]) for k, v in m.items()]
out += ['#define FB_PHYS\tFB_BASE', '#endif', '']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shim', 'board.h'), 'w').write('\n'.join(out))
